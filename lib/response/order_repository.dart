import 'package:dio/dio.dart';
import 'package:flutter/material.dart';
import '../../core/api_client.dart';
import '../../param/order_param.dart';
import '../../response/order_response.dart';

class OrderRepository extends ApiClient{
  Future<OrderResponse> createOrder(OrderParam orderParam) async {
    try {
      var response = await dio.post('order-create', data: orderParam.toJson());
      debugPrint('POST Order : ${response.data}');
      return OrderResponse.fromJson(response.data);
    } on DioException catch (e) {
      throw Exception(e);
    }
  }
}









































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































